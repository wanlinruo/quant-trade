"""表级数据契约与跨表依赖。

字段字典回答“这一列是什么”；本模块回答“这张表为什么存在、以什么
粒度更新、由谁消费，以及怎样连接上下游”。两者保持分离，但依赖边上的
``metrics`` 会由字段血缘生成，避免维护第二份字段清单。
"""

