@dataclass(frozen=True, slots=True)
class _DependencySpec:
    upstream: str
    downstream: str
    kind: K
    keys: tuple[tuple[str, str], ...]
    cardinality: C
    requirement: Q = Q.REQUIRED
    lag: str = "同一生产批次或下游保持灰/红"
    health: str | None = "lineage_freshness"
    note: str = ""


def _spec(up: str, down: str, kind: K, keys: tuple[str, ...] = (), *,
          cardinality: C = C.UNKNOWN, requirement: Q = Q.REQUIRED,
          note: str = "") -> _DependencySpec:
    return _DependencySpec(up, down, kind, tuple((key, key) for key in keys),
                           cardinality, requirement, note=note)


