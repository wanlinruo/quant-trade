def _physical(
    ident: str,
    name: str,
    purpose: str,
    layer: L,
    role: R,
    status: S,
    grain: str,
    key: tuple[str, ...],
    times: tuple[str, ...],
    *,
    partitioned: bool = True,
    sort: tuple[str, ...] | None = None,
    builder: str = UNKNOWN,
    update: str = "按分区原子覆盖",
    finalized: str = UNKNOWN,
    lifecycle: str = "持续维护",
    sources: tuple[str, ...] = (),
    consumers: tuple[str, ...] = (),
    health: str | None = None,
    domain: D | Unclassified,          # 关键字必填，不给默认值
) -> Dataset:
    return Dataset(
        id=ident,
        name=name,
        purpose=purpose,
        layer=layer,
        role=role,
        status=status,
        grain=grain,
        primary_key=key,
        time_columns=times,
        partition_keys=("year",) if partitioned else (),
        sort_keys=sort or key,
        schema_id=ident,
        schema_version=1,
        compatibility="新增列向后兼容；删列、改类型或改语义必须升版本并对账",
        builder=builder,
        update_mode=update,
        finalized_at=finalized,
        lifecycle=lifecycle,
        sources=sources,
        consumers=consumers,
        health_policy=health,
        domain=domain,
    )


