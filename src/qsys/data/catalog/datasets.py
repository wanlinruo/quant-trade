def lineage_edges(registry: Mapping[str, Metric]) -> dict[tuple[str, str], tuple[str, ...]]:
    """从字段级 ``Computed.upstream`` 推导跨表边及其产出指标。"""
    edges: defaultdict[tuple[str, str], set[str]] = defaultdict(set)
    for metric in registry.values():
        if not isinstance(metric.lineage, Computed):
            continue
        for upstream_metric in metric.lineage.upstream:
            upstream = upstream_metric.split(".", 1)[0]
            if upstream != metric.dataset:
                edges[(upstream, metric.dataset)].add(metric.id)
    return {edge: tuple(sorted(metrics)) for edge, metrics in edges.items()}


def build_dependencies(registry: Mapping[str, Metric]) -> tuple[DatasetDependency, ...]:
    inferred = lineage_edges(registry)
    out = []
    for spec in _DEPENDENCY_SPECS:
        out.append(DatasetDependency(
            upstream=spec.upstream,
            downstream=spec.downstream,
            kind=spec.kind,
            join_keys=spec.keys,
            cardinality=spec.cardinality,
            requirement=spec.requirement,
            allowed_lag=spec.lag,
            metrics=inferred.get((spec.upstream, spec.downstream), ()),
            health_policy=spec.health,
            note=spec.note,
        ))
    return tuple(out)
